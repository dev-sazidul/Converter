function soon(
  slug: string,
  name: string,
  description: string,
  category: Exclude<CategoryId, "all">,
  icon: string,
): ToolDefinition {
  return {
    slug,
    name,
    description,
    summary: `${description} This tool is not available yet.`,
    category,
    status: "soon",
    icon,
    accept: [],
    acceptLabel: "file",
    multiple: false,
    reorder: false,
    minFiles: 1,
    maxFiles: 1,
    minMessage: "",
    selectLabel: "",
    dropLabel: "",
    actionLabel: "",
    processingLabel: "",
    seoTitle: `${name} — coming soon — Convarter`,
    seoDescription: `${description} This Convarter tool is planned and not available yet.`,
  };
}

export function getTool(slug: string): ToolDefinition | undefined {
  return tools.find((tool) => tool.slug === slug);
}

export function availableTools(): ToolDefinition[] {
  return tools.filter((tool) => tool.status === "available");
}

